/// The declination at `site`, east-positive, interpolated bilinearly in the table: `None` for
/// a latitude or longitude that is not a number.
///
/// Latitude is clamped to ±90° and longitude wrapped into ±180°. Height is ignored, as the
/// table is taken at sea level: the field's direction changes by well under the grid's own
/// interpolation error across any altitude a vehicle flies at.
pub(crate) fn declination_at(site: Geodetic) -> Option<Radians> {
    // In f32: in f64 the lookup links four times the `.text` in software doubles (DESIGN.md,
    // "Measured cost, by function"), and the answer is returned in f32 anyway.
    let (latitude, longitude) = (site.latitude_deg() as f32, site.longitude_deg() as f32);
    if !latitude.is_finite() || !longitude.is_finite() {
        return None;
    }
    let latitude = latitude.clamp(-90.0, 90.0);
    // One turn either way: a longitude beyond ±540° is not one a receiver reports, and the clamp
    // puts it on the table's edge rather than in a cell it does not name.
    let mut longitude = longitude;
    if longitude > 180.0 {
        longitude -= 360.0;
    }
    if longitude < -180.0 {
        longitude += 360.0;
    }
    let longitude = longitude.clamp(-180.0, 180.0);

    let (row, north) = cell(latitude + 90.0, TABLE.len());
    let (column, east) = cell(longitude + 180.0, TABLE[0].len());
    let (south_row, north_row) = (TABLE.get(row)?, TABLE.get(row + 1)?);
    let corner = |line: &[i16; 37], at: usize| line.get(at).map(|&v| f32::from(v));
    let sw = corner(south_row, column)?;
    // Each corner within half a turn of the south-west one. Near the magnetic poles neighbouring
    // cells sit either side of ±180°, and averaging 179° with −179° gives 0° rather than 180°.
    let near_sw = |value: f32| {
        let (turn, step) = (360.0 / SCALE, value - sw);
        if step > turn / 2.0 {
            value - turn
        } else if step < -turn / 2.0 {
            value + turn
        } else {
            value
        }
    };
    let se = near_sw(corner(south_row, column + 1)?);
    let (nw, ne) = (
        near_sw(corner(north_row, column)?),
        near_sw(corner(north_row, column + 1)?),
    );

    let southern = sw + east * (se - sw);
    let northern = nw + east * (ne - nw);
    let degrees = (southern + north * (northern - southern)) * SCALE;
    Some(Radians::from_radians(wrap_pi(degrees.to_radians())))
}

/// The grid line at or below `offset` degrees from the table's first, and how far past it the
/// point lies as a fraction of the spacing. One short of the last line, so the next one exists;
/// truncation is the floor here, since `offset` is never negative.
fn cell(offset: f32, lines: usize) -> (usize, f32) {
    let index = ((offset / RESOLUTION) as usize).min(lines - 2);
    (index, (offset / RESOLUTION - index as f32).clamp(0.0, 1.0))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn degrees_at(latitude: f64, longitude: f64) -> f32 {
        let radians = declination_at(Geodetic::from_degrees(latitude, longitude, 0.0));
        radians
            .map(|d| d.as_radians().to_degrees())
            .unwrap_or(f32::NAN)
    }

    /// PX4's own `test_geo_lookup.cpp` values at grid points, within its tolerance of
    /// 0.4 + 1.0 degrees: a table from another generator and another epoch of the same model.
    #[test]
    fn grid_points_agree_with_px4s_own_test() {
        assert!((degrees_at(-50.0, -180.0) - 31.7).abs() <= 1.4);
        assert!((degrees_at(-50.0, -100.0) - 27.2).abs() <= 1.4);
    }

    /// The model itself at the table's epoch, from `pygeomag` as `tools/declination.py` reads
    /// it, at three sites between grid points: the table differs from it by the grid's
    /// interpolation error and no more, 0.21° at the worst of these.
    #[test]
    fn between_grid_points_the_table_is_the_model_to_its_interpolation_error() {
        for (latitude, longitude, model) in [
            (56.41, 43.76, 13.8117),
            (47.397742, 8.545594, 3.7347),
            (-33.9, 151.2, 12.8519),
        ] {
            let got = degrees_at(latitude, longitude);
            assert!(
                (got - model).abs() < 0.25,
                "{latitude}, {longitude}: {got} against {model}"
            );
        }
    }

    /// At a grid point the lookup is that cell, in hundredths of a degree.
    #[test]
    fn at_a_grid_point_the_lookup_is_the_cell() {
        let cell = |row: usize, column: usize| f32::from(TABLE[row][column]) * SCALE;
        assert!((degrees_at(-50.0, -180.0) - cell(4, 0)).abs() < 1e-4);
        assert!((degrees_at(-80.0, -170.0) - cell(1, 1)).abs() < 1e-4);
        assert!((degrees_at(90.0, 180.0) - cell(18, 36)).abs() < 1e-4);
    }

    /// On the Antarctic coast, where neighbouring cells sit either side of ±180°: the model
    /// reads −173.3° at (−65°, 135°), and averaging the corners without unwrapping them gives
    /// +8.6°; unwrapped it reads −171.4°. The grid is coarse there, so the bound is the
    /// interpolation error's.
    #[test]
    fn corners_either_side_of_a_half_turn_are_unwrapped_before_interpolating() {
        let got = degrees_at(-65.0, 135.0);
        let off = (got - -173.3 + 180.0).rem_euclid(360.0) - 180.0;
        assert!(off.abs() < 2.5, "{got} against -173.3");
        assert!(got.abs() <= 180.0);
    }

    #[test]
    fn halfway_between_two_columns_is_their_mean() {
        let mean = (degrees_at(-50.0, -180.0) + degrees_at(-50.0, -170.0)) / 2.0;
        assert!((degrees_at(-50.0, -175.0) - mean).abs() < 1e-5);
    }

    #[test]
    fn longitude_wraps_and_latitude_clamps() {
        assert_eq!(degrees_at(0.0, 190.0), degrees_at(0.0, -170.0));
        assert_eq!(degrees_at(0.0, -190.0), degrees_at(0.0, 170.0));
        assert_eq!(degrees_at(95.0, 20.0), degrees_at(90.0, 20.0));
    }

    #[test]
    fn a_site_that_is_not_a_number_has_no_declination() {
        assert!(declination_at(Geodetic::from_degrees(f64::NAN, 0.0, 0.0)).is_none());
        assert!(declination_at(Geodetic::from_degrees(0.0, f64::INFINITY, 0.0)).is_none());
    }
}

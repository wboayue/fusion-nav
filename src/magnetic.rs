//! Magnetic declination from the World Magnetic Model, for the site the origin names.
//!
//! GOALS.md differentiator 7 lists declination as derived: "a magnetic model, given the GNSS
//! origin". The filter reads it from here when it places an origin and no caller has set one;
//! see [`Eskf::set_magnetic_declination`](crate::Eskf::set_magnetic_declination).
//!
//! [`TABLE`] is the model's declination every 10° of latitude and longitude at one epoch, and
//! [`declination_at`] interpolates it bilinearly. `tools/declination.py` generates the table from
//! NCEI's coefficient file, and its `--drift` says when the epoch has gone stale ([table]). The
//! WMM is US-government work in the public domain, so the table carries no licence.
//!
//! It costs about 2.5 KB of flash ([measured]). Hence the feature, which GOALS.md's
//! derived-configuration table asks for, "optional, for its flash cost": off, none of it is linked.
//!
//! PX4 (`geo_magnetic_tables.hpp`) and ArduPilot (`AP_Declination`) ship the same shape, and
//! neither takes a date: a table is fixed at the epoch it was generated for, and secular
//! variation accumulates until it is regenerated. PX4's is the one `tools/ulog2replay.py` carries
//! to reproduce EKF2's own declination, so the replay harness's `declination_model=` key, this
//! table at each log's origin, sits beside the declination EKF2 applied there.
//!
//! [table]: https://github.com/wboayue/fusion-nav/blob/main/GOALS.md#magnetic-declination-from-a-table-read-where-the-origin-is-placed
//! [measured]: https://github.com/wboayue/fusion-nav/blob/main/DESIGN.md#measured-cost-by-function

